// AI Agent Monitor — CYD 펌웨어: 설정 저장(NVS)과 WiFi 캡티브 포털
//
// Task 9 도 **화면을 붙이지 않는다.** 여기서 확인하는 것은 두 가지뿐이다:
// 설정이 재부팅을 견디는가, 그리고 설정 포털이 실제로 뜨는가. 판정은 전부
// 시리얼로 한다. 화면·mDNS·WebSocket·암호는 여전히 다음 태스크들이다.

#pragma once

#include <Arduino.h>

// ─────────────────────────────────────────────────────────────────────────────
// 토큰은 **평문으로** NVS 에 저장된다.
//
// 플래시 암호화를 켜지 않는 한, 기기를 주운 사람이 플래시를 덤프해서 읽을 수
// 있다. iOS Keychain 과 다르고, 여기서 그걸 흉내 낼 방법도 없다 — 키를 어디에
// 두든 결국 같은 플래시 안이다. 스펙 7.2 가 이 위험을 받아들였고, 대응은
// 암호화가 아니라 **맥에서의 기기별 페어링 해제**다. 토큰이 새어 나가면 맥에서
// 그 기기를 해제하면 되고, 그 순간 토큰은 아무 데도 못 쓴다.
//
// 그러니 이 파일이 지켜야 하는 것은 "토큰을 숨기는 것" 이 아니라 **토큰을
// 우리 손으로 먼저 흘리지 않는 것**이다. 구체적인 금지 목록은 `config.cpp` 의
// `wifiConnectOrPortal()` 바로 위에 있다.
// ─────────────────────────────────────────────────────────────────────────────

/// 기기 설정. `configLoad` 로 채우고, 두 필드는 수명이 달라서 저장 함수도 따로다.
struct Config {
    /// 맥 호스트명 또는 IP. **비어 있으면 mDNS 자동 탐색**이라는 뜻이고 그게
    /// 기본 동작이다(포털에서 칸을 비워 두면 된다). 설정 포털이 채운다.
    String macHost;

    /// 페어링 토큰. 비어 있으면 미페어링. 비어 있지 **않다면** 반드시
    /// `configTokenIsValid` 를 통과한 값이다 — `configLoad` 와 `configSaveToken`
    /// 이 값이 드나드는 두 경계에서 모두 걸러 내기 때문이다. 페어링(Task 13)이
    /// 채우고, 언페어링이 지운다.
    String token;
};

/// NVS 에서 설정을 읽어 `c` 를 채운다.
///
/// **반환값은 "저장된 적이 있는가" 이지 "페어링됐는가" 가 아니다.** 두 질문은
/// 서로 다르고 나중에 갈린다 — Task 14 는 "한 번도 설정된 적 없음" 에는 초기
/// 설정 안내를, "설정은 끝났는데 아직 페어링 전" 에는 페어링 키패드를 띄운다.
/// 하나의 bool 에 뭉쳐 두면 그 분기를 만들 수가 없다. 페어링 여부는
/// `configIsPaired` 로 따로 묻는다.
///
/// 판정 근거는 읽기 전용 `Preferences::begin("aim", true)` 의 반환값이다.
/// 네임스페이스가 아직 없으면 `nvs_open` 이 `ESP_ERR_NVS_NOT_FOUND` 를 내고
/// `begin` 이 false 를 돌려준다(nvs.h: "id namespace doesn't exist yet and mode
/// is NVS_READONLY").
///
/// 엄밀히 말하면 false 는 "NVS 를 읽을 수 없다" 이지 "한 번도 쓴 적 없다" 가
/// 아니다 — 파티션이 없거나 드라이버가 초기화되지 않아도 false 다. **호출자에게
/// 두 경우는 같은 뜻이다**: 어느 쪽이든 우리가 아는 설정이 없으니 설정부터
/// 받아야 한다. 어느 경우든 `c` 는 기본값(둘 다 빈 문자열)으로 채워진다.
bool configLoad(Config &c);

/// 페어링됐는가. `configLoad` 의 반환값과는 **다른 질문**이다(위 참고).
bool configIsPaired(const Config &c);

/// 토큰이 맥이 발급하는 형식인가 — **32자 소문자 hex**.
///
/// 맥은 128비트 난수를 `{:016x}{:016x}` 로 찍어 토큰을 만들고, 저장해 둔 토큰을
/// 다시 읽을 때도 같은 검사를 건다(`src-tauri/src/ble/pairing.rs` 의
/// `is_valid_lowercase_hex(&token, 32)` — 형식이 깨진 항목은 조용히 버려서
/// 인증 우회로 이어지지 않게 한다). 이쪽도 발급자와 같은 기준을 쓴다.
///
/// **왜 길이만 보면 안 되는가.** 길이만 보면 NVS 가 손상돼 32자짜리 쓰레기가
/// 남았을 때 그대로 통과하고, 그 값은 Task 10~11 에서 hex 디코드를 거쳐 HMAC
/// 키 자리(16바이트)까지 흘러간 뒤에야 실패한다. 그리고 이 기기에는 왜 실패했는지
/// 말해 줄 화면이 없다. 값이 들어오는 경계에서 거르는 것이 가장 싸고, 무엇이
/// 잘못됐는지 말할 맥락이 아직 남아 있는 유일한 자리다.
///
/// 대문자 hex 도 거절한다. HMAC 만 놓고 보면 대문자여도 같은 16바이트로
/// 디코드되니 암호가 깨지지는 않는다 — 거절하는 이유는 그게 아니라 **그 값이
/// 맥의 페어링 흐름에서 나온 값이 아니기 때문**이다. 발급자와 같은 형식만 받는다.
bool configTokenIsValid(const String &token);

/// `c.macHost` 만 NVS 에 쓴다. **토큰은 건드리지 않는다.**
///
/// 브리프의 `configSave(const Config&)` 는 두 값을 한꺼번에 썼다. 그러면
/// `configLoad` 를 거치지 않은 `Config` 를 들고 이 함수를 부르는 순간 멀쩡한
/// 토큰이 빈 문자열로 덮인다 — 그리고 그 사고는 "맥 주소를 저장했다" 는 코드
/// 옆에서 일어나므로 아무도 의심하지 않는다. 맥 주소(포털이 정한다)와
/// 토큰(페어링이 정한다)은 수명이 다르니 쓰는 함수도 갈라 둔다.
void configSaveHost(const Config &c);

/// 토큰을 검사해서 NVS 에 쓰고, 성공하면 `c.token` 도 같이 갱신한다.
///
/// 형식이 틀린 토큰은 **쓰지 않고** false 를 돌려준다 — 값이 들어오는 두 경계
/// (NVS 읽기, 여기) 양쪽에 같은 검사를 둔다. Task 13 이 맥에게서 받은 값을
/// 그대로 넣을 자리이므로, 맥이 아닌 무언가가 보낸 값이 플래시에 눌어붙는
/// 지점이 바로 여기다.
bool configSaveToken(Config &c, const String &token);

/// 토큰을 NVS 와 `c` 양쪽에서 지운다.
///
/// `Config&` 를 받는 이유: 브리프의 인자 없는 `configClearToken()` 은 NVS 만
/// 비우고 메모리의 `c.token` 은 그대로 두므로, 지운 직후에도
/// `configIsPaired(c)` 가 계속 "페어링됨" 이라고 답한다. 둘을 갈라 놓지 않는다.
void configClearToken(Config &c);

/// 저장된 자격증명으로 WiFi 에 붙어 보고, 실패하면 설정 포털(`AIM-Setup` AP)을
/// 연다. 연결되면 true.
///
/// 포털에서 맥 주소를 받으면 `c.macHost` 를 갱신하고 NVS 에 쓴다. **값이
/// 달라졌을 때만 쓴다** — 상시 전원 기기는 자주 재부팅될 수 있고, 매 부팅마다
/// 같은 값을 다시 쓸 이유가 없다(플래시 쓰기 횟수는 유한하다).
///
/// **이 함수는 블로킹이다** — 포털이 열려 있는 동안 `loop()` 는 돌지 않는다.
/// 여기서만 괜찮은 이유는 하나다: 이 함수는 부팅 때, **WebSocket 이 붙기
/// 전에** 돈다. 그것이 `main.cpp` 상단 30초 예산을 어겨도 되는 유일한 근거다.
///
/// Task 12 이후에 **런타임 중** 포털을 다시 여는 길을 만든다면(맥 주소 변경,
/// WiFi 재설정), 포털을 열기 전에 **WebSocket 을 명시적으로 끊어라.** 끊지 않고
/// 열면 맥은 90초 뒤 그 연결을 죽은 것으로 처리하고, 포털에서 돌아온 기기는
/// 자기가 왜 끊겼는지 모른 채 재연결을 시작한다.
///
/// 무한정 기다리지는 않는다. false 를 돌려줄 수 있고, 그때 무엇을 할지는
/// 호출자가 정한다 — `main.cpp` 의 T9-D 블록을 보라.
bool wifiConnectOrPortal(Config &c);
